// Execute a structure plan. params: { plan, dry_run, allow_substitute, verify, max_place }
var cfg = (typeof params === 'object' && params !== null) ? params : {};
var plan = cfg.plan;
if (!plan || !plan.tasks || !plan.tasks.length) {
  return { ok: false, error: 'place_build_plan needs params.plan generated by plan_structure' };
}

var ranks = { foundation: 0, floor: 1, corner: 2, wall: 3, window: 4, railing: 5,
  roof: 6, detail: 7 };
var tasks = plan.tasks.slice(0);
tasks.sort(function (a, b) {
  var ra = ranks[a.phase] !== undefined ? ranks[a.phase] : 7;
  var rb = ranks[b.phase] !== undefined ? ranks[b.phase] : 7;
  if (ra !== rb) return ra - rb;
  if (a.y !== b.y) return a.y - b.y;
  if (a.x !== b.x) return a.x - b.x;
  return a.z - b.z;
});

var inventory = drone.state().inventory;
var substitute = cfg.allow_substitute !== false;
var missing = [];
var requirement = {};
for (var r = 0; r < tasks.length; r++) {
  requirement[tasks[r].block] = (requirement[tasks[r].block] || 0) + 1;
}

if (cfg.dry_run === true) {
  var report = {};
  for (var material in requirement) {
    report[material] = { required: requirement[material],
      have: countInInventory(inventory, material) };
    if (report[material].have < report[material].required) missing.push(material);
  }
  return { ok: true, dryRun: true, tasks: tasks.length,
    clear: (plan.clear || []).length, materials: report,
    missingMaterials: missing, bounds: { x1: plan.x1, z1: plan.z1, x2: plan.x2, z2: plan.z2,
      floorY: plan.floorY, maxY: plan.maxY } };
}

// 1) Clear obstacles from the top down.
var cleared = 0;
var clearFailed = 0;
if (cfg.clear !== false && plan.clear) {
  var clearList = plan.clear.slice(0);
  clearList.sort(function (a, b) { return b.y - a.y; });
  var clearCap = clamp(cfg.max_clear || clearList.length, 0, SKILL_LIMITS.clearCapMax);
  for (var c = 0; c < clearList.length && c < clearCap; c++) {
    var obstacle = clearList[c];
    try {
      drone.breakBlock({ x: obstacle.x, y: obstacle.y, z: obstacle.z });
      cleared++;
    } catch (clearError) {
      clearFailed++;
    }
  }
}

// 2) Place in phase order.
var placed = 0;
var alreadyThere = 0;
var failed = 0;
var substituted = 0;
var consecutive = 0;
var maxFailures = clamp(cfg.max_failures || 12, 1, SKILL_LIMITS.buildFailuresMax);
var limit = clamp(cfg.max_place || tasks.length, 1, SKILL_LIMITS.budget800);
var attemptedWithdraw = {};
var used = {};

for (var t = 0; t < tasks.length && t < limit; t++) {
  var task = tasks[t];
  var block = task.block;

  // Refresh inventory every few placements so material checks stay honest.
  if (t > 0 && t % 6 === 0) inventory = drone.state().inventory;

  var available = countInInventory(inventory, block);
  if (available <= 0 && !attemptedWithdraw[block]) {
    attemptedWithdraw[block] = true;
    try {
      skills.call('withdraw_items', { filter: block, count: Math.min(64, requirement[block] || 16) });
      inventory = drone.state().inventory;
      available = countInInventory(inventory, block);
    } catch (withdrawError) {
      log('material lookup failed for ' + block + ': ' + withdrawError.message);
    }
  }

  var chosen = block;
  if (available <= 0) {
    if (!substitute) {
      missing.push(block);
      failed++;
      if (++consecutive >= maxFailures) break;
      continue;
    }
    chosen = 'any';
    substituted++;
  }

  try {
    var result = drone.placeBlock({ x: task.x, y: task.y, z: task.z, block: chosen });
    if (result && result.placed) {
      placed++;
      used[chosen] = (used[chosen] || 0) + 1;
      consecutive = 0;
    } else {
      failed++;
      consecutive++;
    }
  } catch (placeError) {
    var message = String(placeError.message || '');
    if (message.indexOf('occupied') >= 0) {
      try {
        var existing = drone.getBlock({ x: task.x, y: task.y, z: task.z });
        if (existing && nameMatches(existing.name, existing.registryName, block, existing.oreDict)) alreadyThere++;
        else failed++;
      } catch (checkError) {
        failed++;
      }
    } else {
      failed++;
      log('place failed at ' + task.x + ',' + task.y + ',' + task.z + ': ' + message);
    }
    consecutive++;
  }
  if (consecutive >= maxFailures) break;
}

// 3) Verify with a box count when requested.
var verification = null;
if (cfg.verify !== false) {
  var y1 = Math.min(plan.floorY, plan.maxY);
  var y2 = Math.max(plan.floorY, plan.maxY);
  try {
    var box = drone.getBlocksInBox({ x1: plan.x1, y1: y1, z1: plan.z1,
      x2: plan.x2, y2: y2, z2: plan.z2, include_air: false });
    verification = { nonAir: box.count, total: box.totalVoxels,
      counts: box.countsByType };
  } catch (verifyError) {
    verification = { error: verifyError.message };
  }
}

return {
  ok: placed + alreadyThere > 0,
  cleared: cleared,
  clearFailed: clearFailed,
  placed: placed,
  alreadyThere: alreadyThere,
  failed: failed,
  substituted: substituted,
  materialsUsed: used,
  missingMaterials: missing,
  verification: verification,
  hint: missing.length
    ? 'missing materials: ' + missing.join(', ') + '; gather or withdraw them and re-run'
    : ''
};
