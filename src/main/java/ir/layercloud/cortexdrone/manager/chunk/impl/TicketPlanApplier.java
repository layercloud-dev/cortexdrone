package ir.layercloud.cortexdrone.manager.chunk.impl;

import ir.layercloud.cortexdrone.DroneController;
import ir.layercloud.cortexdrone.manager.chunk.PlayerChunkOwnership;
import ir.layercloud.cortexdrone.service.world.ChunkAccess;
import net.minecraft.world.ChunkCoordIntPair;
import net.minecraft.world.WorldServer;
import net.minecraftforge.common.ForgeChunkManager;

import java.util.*;

/**
 * Applies a chunk plan to a Forge ticket.
 *
 * <p>Extracted from {@code ChunkLoadingManager}. Four ordered passes:</p>
 * <ol>
 *   <li>release claims no longer wanted, after a grace period and only when no
 *       player can see the chunk and no drone is near it;</li>
 *   <li>claim the desired set, highest priority first, evicting the lowest;</li>
 *   <li>reorder so the highest-priority chunk sits at the tail;</li>
 *   <li>load the missing chunks nearest-first under a per-update budget.</li>
 * </ol>
 *
 * <p>Forge tickets claim chunks; they do not generate them. The load pass is what
 * actually makes a chunk readable, and its budget is why flight does not stall on
 * world generation.</p>
 */
@SuppressWarnings("unused")
final class TicketPlanApplier {
    /**
     * A released claim waits this many ticks before it is dropped.
     */
    private static final int RELEASE_GRACE_TICKS = 60;
    /**
     * Chunks generated per ticket update.
     */
    static final int LOAD_BUDGET = 3;

    /**
     * Everything the applier needs from the manager.
     */
    interface Host {
        ForgeTicketOps ticketOps();

        /**
         * True when a drone other than this one is near the chunk.
         */
        boolean isAnyDroneNear(net.minecraft.world.World world, ChunkCoordIntPair pair);

        /**
         * Loads one chunk, recording it as AI-loaded.
         */
        void loadChunk(WorldServer world, ChunkCoordIntPair pair);

        /**
         * Pending release deadlines per ticket.
         */
        Map<ForgeChunkManager.Ticket, Map<ChunkCoordIntPair, Long>> releaseAt();
    }

    private final Host host;

    TicketPlanApplier(Host host) {
        this.host = host;
    }

    /**
     * Applies {@code plan} to {@code ticket}.
     *
     * @return the number of chunks actually generated by this pass
     */
    int apply(WorldServer world, DroneController controller,
              ForgeChunkManager.Ticket ticket, List<ChunkCoordIntPair> plan) {
        if (world == null || ticket == null || plan == null || plan.isEmpty()) return 0;
        ForgeTicketOps.configure(ticket);

        int depth = ticket.getChunkListDepth();
        if (depth <= 0) return 0;
        depth = Math.min(depth, NavigationChunkPlanner.MAX_TICKET_CHUNKS);
        List<ChunkCoordIntPair> desired = plan.size() > depth ? plan.subList(0, depth) : plan;
        Set<ChunkCoordIntPair> desiredSet = new HashSet<>(desired);

        Map<ChunkCoordIntPair, Long> pending = this.host.releaseAt().get(ticket);
        if (pending == null) {
            pending = new HashMap<>();
            this.host.releaseAt().put(ticket, pending);
        }
        long now = world.getTotalWorldTime();
        releaseUnwanted(world, ticket, desiredSet, pending, now);
        Set<ChunkCoordIntPair> held = claimDesired(world, ticket, desired, desiredSet,
                pending, depth);
        pending.keySet().retainAll(held);
        reorder(ticket, desired, held);
        return loadMissing(world, desired, held, LOAD_BUDGET);
    }

    /**
     * Pass 1: drop claims no longer wanted, after the grace period.
     */
    private void releaseUnwanted(WorldServer world, ForgeChunkManager.Ticket ticket,
                                 Set<ChunkCoordIntPair> desired,
                                 Map<ChunkCoordIntPair, Long> pending, long now) {
        for (ChunkCoordIntPair old : new HashSet<>(ticket.getChunkList())) {
            if (desired.contains(old) || isProtected(world, old)) {
                pending.remove(old);
                continue;
            }
            Long due = pending.get(old);
            if (due == null) {
                pending.put(old, now + RELEASE_GRACE_TICKS);
            } else if (now >= due) {
                pending.remove(old);
                this.host.ticketOps().unforce(ticket, old);
            }
        }
    }

    /**
     * Pass 2: claim the desired set, evicting the lowest-priority claim.
     */
    private Set<ChunkCoordIntPair> claimDesired(WorldServer world, ForgeChunkManager.Ticket ticket,
                                                List<ChunkCoordIntPair> desired,
                                                Set<ChunkCoordIntPair> desiredSet,
                                                Map<ChunkCoordIntPair, Long> pending, int depth) {
        Set<ChunkCoordIntPair> held = new HashSet<>(ticket.getChunkList());
        for (ChunkCoordIntPair pair : desired) {
            if (isProtected(world, pair) || held.contains(pair)) continue;
            while (held.size() >= depth) {
                ChunkCoordIntPair evict = ForgeTicketOps.firstNotIn(ticket.getChunkList(), desiredSet);
                if (evict == null) break;
                pending.remove(evict);
                this.host.ticketOps().unforce(ticket, evict);
                held.remove(evict);
            }
            if (held.size() >= depth) break;
            if (this.host.ticketOps().force(ticket, pair)) held.add(pair);
        }
        return held;
    }

    /**
     * Pass 3: highest-priority chunk at the tail of the ticket list.
     */
    private void reorder(ForgeChunkManager.Ticket ticket, List<ChunkCoordIntPair> desired,
                         Set<ChunkCoordIntPair> held) {
        for (int i = desired.size() - 1; i >= 0; i--) {
            ChunkCoordIntPair pair = desired.get(i);
            if (held.contains(pair)) this.host.ticketOps().reorder(ticket, pair);
        }
    }

    /**
     * Pass 4: generate missing claimed chunks, nearest first, within budget.
     */
    private int loadMissing(WorldServer world, List<ChunkCoordIntPair> desired,
                            Set<ChunkCoordIntPair> held, int budget) {
        int loads = 0;
        for (ChunkCoordIntPair pair : desired) {
            if (loads >= budget) break;
            if (!held.contains(pair) || isProtected(world, pair)) continue;
            if (ChunkAccess.isLoaded(world, pair.chunkXPos, pair.chunkZPos)) continue;
            this.host.loadChunk(world, pair);
            loads++;
        }
        return loads;
    }

    /**
     * Loads up to {@code budget} chunks from a plan, skipping protected ones.
     */
    int loadHotChunks(WorldServer world, List<ChunkCoordIntPair> plan, int budget) {
        int loaded = 0;
        for (ChunkCoordIntPair pair : plan) {
            if (loaded >= budget) break;
            if (isProtected(world, pair)) continue;
            if (ChunkAccess.isLoaded(world, pair.chunkXPos, pair.chunkZPos)) continue;
            this.host.loadChunk(world, pair);
            loaded++;
        }
        return loaded;
    }

    /**
     * A chunk inside a player's view, or near another drone, is not ours to touch.
     */
    private boolean isProtected(net.minecraft.world.World world, ChunkCoordIntPair pair) {
        return PlayerChunkOwnership.isWithinAnyPlayerView(world, pair.chunkXPos, pair.chunkZPos)
                || this.host.isAnyDroneNear(world, pair);
    }
}
